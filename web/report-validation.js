/** Validate structure of a user-supplied NEAR Sandbox execution report.
 * Passing validation does NOT establish authenticity of the uploaded file.
 */
const isObject=x=>x!==null&&typeof x==='object'&&!Array.isArray(x);
// Only compare JSON data. Report files come from JSON.parse(), not arbitrary JS objects.
// Unlike JSON.stringify equality, this respects object key order independence.
function sameJson(a,b) {
  if (Object.is(a,b)) return true;
  if (Array.isArray(a) || Array.isArray(b))
    return Array.isArray(a)&&Array.isArray(b)&&a.length===b.length&&a.every((x,i)=>sameJson(x,b[i]));
  if (!isObject(a)||!isObject(b)) return false;
  const keys=Object.keys(a);
  return keys.length===Object.keys(b).length&&keys.every(k=>Object.hasOwn(b,k)&&sameJson(a[k],b[k]));
}
export function validateExecutionReport(r) {
  if(isObject(r)&&r.schemaVersion===1&&typeof r.name==='string'&&Array.isArray(r.steps)&&!r.kind)
    throw new Error('You selected a TEST PLAN, not an execution report. A plan is only instructions. Run it using the NEAR Sandbox CLI, then upload the generated report.json. To test the viewer without Terminal, download protected.json from the linked successful GitHub Actions run.');
  if(isObject(r)&&r.kind==='observed-near-transaction')
    throw new Error('This is live transaction evidence, not a Sandbox execution report. Upload a report generated by sandbox/scripts/scan-contract.mjs.');
  if(!isObject(r)||r.schemaVersion!==1||r.kind!=='user-contract-execution-report'||r.engine!=='near-sandbox')
    throw new Error('Not a StateRift NEAR Sandbox execution report. Choose an execution report (protected.json, vulnerable.json or contract-report.json), not a test plan.');
  if(typeof r.wasmSha256!=='string'||!/^[0-9a-f]{64}$/.test(r.wasmSha256))
    throw new Error('Invalid WASM fingerprint.');
  if(typeof r.planName!=='string'||r.planName.length>96||r.planName.length===0)
    throw new Error('Invalid plan name.');
  if(typeof r.passed!=='boolean'||!Array.isArray(r.steps)||r.steps.length<1||r.steps.length>40)
    throw new Error('Invalid execution steps.');
  for(const [i,step] of r.steps.entries()) {
    if(!isObject(step)||!['call','assertView'].includes(step.type)||typeof step.method!=='string'||step.method.length>128||typeof step.passed!=='boolean')
      throw new Error('Invalid step '+(i+1)+'.');
    if(step.type==='call') {
      if(!['success','failure','execution-error'].includes(step.observed)||!['success','failure'].includes(step.expect))
        throw new Error('Invalid call outcome in step '+(i+1)+'.');
      if(step.receiptFailures!==undefined&&(!Number.isSafeInteger(step.receiptFailures)||step.receiptFailures<0))
        throw new Error('Invalid receipt failure count.');
      if(step.receiptCount!==undefined&&(!Number.isSafeInteger(step.receiptCount)||step.receiptCount<0))
        throw new Error('Invalid receipt count.');
      if(step.observed==='execution-error'&&step.passed)
        throw new Error('Execution errors cannot satisfy a contract expectation.');
      if(step.passed&&step.observed!==step.expect)
        throw new Error('Call step cannot PASS with a mismatched observed outcome.');
      if(step.receiptCount!==undefined&&step.receiptFailures!==undefined&&step.receiptFailures>step.receiptCount)
        throw new Error('Failed receipt count exceeds observed receipt count.');
      if(step.passed&&step.expectReceiptFailure!==undefined){
        if(typeof step.expectReceiptFailure!=='boolean')
          throw new Error('Invalid async receipt failure expectation.');
        if(step.receiptCount===undefined||step.receiptFailures===undefined||step.receiptCount===0||
          (step.receiptFailures>0)!==step.expectReceiptFailure)
          throw new Error('Passing call contradicts recorded async receipt expectation.');
      }
      if(step.receipts!==undefined&&(!Array.isArray(step.receipts)||step.receipts.length>24))
        throw new Error('Invalid receipt list.');
      if(step.error!==undefined&&step.passed)
        throw new Error('A call with a recorded execution error cannot pass.');
    } else {
      if(!Object.hasOwn(step,'expected')||!Object.hasOwn(step,'actual'))
        throw new Error('Missing view assertion evidence in step '+(i+1)+'.');
      if(step.error!==undefined&&step.passed)
        throw new Error('A failed view call cannot pass.');
      if(step.error===undefined&&step.passed!==sameJson(step.expected,step.actual))
        throw new Error('View assertion verdict disagrees with expected and actual state in step '+(i+1)+'.');
    }
  }
  if(r.passed!==r.steps.every(s=>s.passed))throw new Error('Overall verdict disagrees with step assertions.');
  return r;
}
